"""
Phase 1 - Data Understanding pipeline.

Run from the project root:
    python -m scripts.run_phase1

Outputs (reports/phase1/):
    data_dictionary.csv       - every column with meaning, timing and recommendation
    missing_values.csv        - missing count / % per column
    maturity_by_cohort.csv    - status mix and default rate by issue year x term
    data_quality_report.md    - consolidated, human-readable report
And data/interim/loan_raw.parquet - an unmodified Parquet copy of the raw file.
"""
import pandas as pd

from src.config import PHASE1_DIR, TARGET_SPEC_COL
from src.data import quality as q
from src.data.dictionary import build_data_dictionary
from src.data.load import load_raw, save_raw_parquet, validate_raw
from src.data.target import define_target, target_summary
from src.utils import md_table

NUMERIC_TO_PROFILE = [
    "loan_amnt", "annual_inc", "dti", "int_rate", "installment", "revol_bal",
    "revol_util", "open_acc", "total_acc", "delinq_2yrs", "inq_last_6mths", "pub_rec",
]
CATEGORICAL_TO_PROFILE = [
    "term", "grade", "emp_length", "home_ownership", "verification_status",
    "purpose", "pub_rec_bankruptcies",
]
MISSINGNESS_TO_TEST = [
    "mths_since_last_delinq", "mths_since_last_record", "emp_length",
    "emp_title", "pub_rec_bankruptcies", "revol_util", "desc",
]


def kv_table(d: dict) -> str:
    return md_table(pd.DataFrame({"metric": list(d), "value": list(d.values())}))


def main() -> None:
    PHASE1_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Load ----------------------------------------------------------------
    df = load_raw()
    for warning in validate_raw(df):
        print(f"WARNING: {warning}")
    save_raw_parquet(df)

    # 2. Structure ------------------------------------------------------------
    overview = q.dataset_overview(df)
    dictionary = build_data_dictionary(df)
    missing = q.missing_value_report(df)
    dups = q.duplicate_report(df)
    constants = q.constant_columns(df)

    # 3. Values ---------------------------------------------------------------
    formats = q.format_issues(df)
    dates = q.date_checks(df)
    num_prof = q.numeric_profile(df, NUMERIC_TO_PROFILE)
    cat_prof = q.category_profile(df, CATEGORICAL_TO_PROFILE)

    # 4. Target, maturity, leakage -------------------------------------------
    status = target_summary(df)
    resolved = define_target(df)
    maturity = q.maturity_report(df)
    current_age = q.current_loans_age(df)
    timing = q.default_timing(df)
    leakage = q.leakage_evidence(df)
    miss_vs_def = q.missingness_vs_default(df, MISSINGNESS_TO_TEST)

    # 5. Save tables ----------------------------------------------------------
    dictionary.to_csv(PHASE1_DIR / "data_dictionary.csv", index=False)
    missing.to_csv(PHASE1_DIR / "missing_values.csv", index=False)
    maturity.to_csv(PHASE1_DIR / "maturity_by_cohort.csv", index=False)

    rec_counts = (
        dictionary["recommendation"].str.split(" - ").str[0].value_counts()
        .rename_axis("treatment").reset_index(name="columns")
    )
    populated = dictionary[dictionary["missing_pct"] < 100]
    band_counts = missing["band"].value_counts().reindex(
        ["100%", "50-<100%", "5-50%", "0-5%", "0%"]).rename_axis("missing band").reset_index(name="columns")

    # 6. Markdown report ------------------------------------------------------
    sections = [
        "# Phase 1 - Data Quality Report: LendingClub loans 2007-2011\n",
        "_Generated by `scripts/run_phase1.py`. All figures are computed from `data/raw/loan.csv`._\n",
        "## 1. Dataset overview\n", kv_table(overview),
        "\n## 2. Missing values\n", md_table(band_counts),
        "\nPopulated columns with missing values:\n",
        md_table(missing[(missing.missing_pct > 0) & (missing.missing_pct < 100)]),
        "\n## 3. Duplicates\n", kv_table(dups),
        "\n## 4. Constant columns (single value)\n", md_table(constants),
        "\n## 5. Format issues to fix in Phase 2\n", md_table(formats),
        "\n## 6. Date checks\n", kv_table(dates),
        "\n## 7. Numeric profile (outliers flagged with the 1.5 x IQR rule; not yet treated)\n",
        md_table(num_prof),
        "\n## 8. Categorical profile\n", md_table(cat_prof),
        "\n## 9. Target variable\n", md_table(status),
        f"\nResolved loans (original definition): **{len(resolved):,}**; "
        f"charged-off rate **{resolved[TARGET_SPEC_COL].mean() * 100:.2f}%**. "
        "The modelling target (default within 36 months) is built in Phase 2.\n",
        "\n## 10. Outcome maturity by cohort\n", md_table(maturity),
        "\nAge of `Current` loans at the inferred snapshot:\n", kv_table(current_age),
        "\nWhen charged-off loans stopped paying (months on book at last payment):\n",
        md_table(timing),
        "\n## 11. Leakage evidence: repayment fields by outcome (means)\n", md_table(leakage),
        "\n## 12. Is missingness informative? (resolved loans)\n", md_table(miss_vs_def),
        "\n## 13. Column treatment summary (detail in data_dictionary.csv)\n", md_table(rec_counts),
        "\n### Populated columns\n",
        md_table(populated[["column", "group", "timing", "missing_pct", "n_unique", "recommendation"]]),
    ]
    (PHASE1_DIR / "data_quality_report.md").write_text("\n".join(sections), encoding="utf-8")

    print(f"Loaded {overview['rows']:,} rows x {overview['columns']} columns")
    print(f"Resolved loans: {len(resolved):,} | default rate {resolved[TARGET_SPEC_COL].mean():.4f}")
    print(f"Reports written to {PHASE1_DIR}")


if __name__ == "__main__":
    main()
